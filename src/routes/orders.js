const router = require('express').Router();
const crypto = require('crypto');
const config = require('../config');
const { withTenant, UUID_RE } = require('../db/tenantDb');
const { publishOrderCreated } = require('../kafka/producer');
const { listOrdersNaive, listOrdersOptimized, getOrder } = require('../services/orderQueries');
const { requestInvoice } = require('../services/invoiceClient');

function validateOrder(body) {
  if (!body || typeof body !== 'object') return 'Body required';
  const { customerName, items } = body;
  if (typeof customerName !== 'string' || !customerName.trim() || customerName.length > 120) return 'customerName required (max 120 chars)';
  if (!Array.isArray(items) || items.length < 1 || items.length > 20) return 'items must be an array of 1-20 entries';
  for (const it of items) {
    if (!it || !UUID_RE.test(String(it.productId))) return 'each item needs a valid productId (uuid)';
    if (!Number.isInteger(it.quantity) || it.quantity < 1 || it.quantity > 100) return 'quantity must be an integer 1-100';
  }
  return null;
}

// POST /api/v1/orders  -> 202 Accepted, event published to Kafka, processed async
router.post('/', async (req, res, next) => {
  const t0 = process.hrtime.bigint();
  try {
    const err = validateOrder(req.body);
    if (err) return res.status(400).json({ error: 'VALIDATION_ERROR', message: err });

    // merge duplicate product lines
    const merged = new Map();
    for (const it of req.body.items) merged.set(it.productId, (merged.get(it.productId) || 0) + it.quantity);

    const event = {
      type: 'OrderCreated',
      version: 1,
      eventId: crypto.randomUUID(),
      orderId: crypto.randomUUID(),
      tenantId: req.tenant.id,           // <- from JWT, never from the body
      tenantSlug: req.tenant.slug,
      userId: req.user.id,
      customerName: req.body.customerName.trim(),
      items: [...merged].map(([productId, quantity]) => ({ productId, quantity })),
      createdAt: new Date().toISOString(),
    };
    const kafkaMeta = await publishOrderCreated(event);
    const ms = Number(process.hrtime.bigint() - t0) / 1e6;
    res.status(202)
      .location(`/api/v1/orders/${event.orderId}`)
      .json({
        status: 'ACCEPTED',
        orderId: event.orderId,
        eventId: event.eventId,
        kafka: { topic: config.kafka.topic, key: event.tenantId, ...kafkaMeta },
        responseMs: Number(ms.toFixed(1)),
        statusUrl: `/api/v1/orders/${event.orderId}`,
      });
  } catch (e) {
    if (/kafka|broker|connect/i.test(e.message)) {
      return res.status(503).json({ error: 'EVENT_BUS_UNAVAILABLE', message: e.message });
    }
    next(e);
  }
});

// GET /api/v1/orders?mode=naive|optimized&limit=50  (N+1 demo)
router.get('/', async (req, res, next) => {
  try {
    const mode = req.query.mode === 'naive' ? 'naive' : 'optimized';
    const limit = Math.min(Math.max(parseInt(req.query.limit, 10) || 50, 1), 200);
    const t0 = process.hrtime.bigint();
    const out = await withTenant(req.tenant.id, async (db) => {
      const orders = mode === 'naive' ? await listOrdersNaive(db, { limit }) : await listOrdersOptimized(db, { limit });
      return { orders, queries: db.queryCount };
    });
    const ms = Number(process.hrtime.bigint() - t0) / 1e6;
    res.set('x-query-count', String(out.queries)).set('x-query-ms', ms.toFixed(1));
    res.json({ mode, queries: out.queries, ms: Number(ms.toFixed(1)), count: out.orders.length, orders: out.orders });
  } catch (e) { next(e); }
});

router.get('/:id', async (req, res, next) => {
  try {
    if (!UUID_RE.test(req.params.id)) return res.status(400).json({ error: 'INVALID_ID' });
    const order = await withTenant(req.tenant.id, (db) => getOrder(db, req.params.id));
    if (!order) return res.status(404).json({ error: 'NOT_FOUND', message: 'Order not found (or still being processed by the consumer)' });
    res.json(order);
  } catch (e) { next(e); }
});

// GET /api/v1/orders/:id/invoice  -> PDF generated by the serverless function
router.get('/:id/invoice', async (req, res, next) => {
  try {
    if (!UUID_RE.test(req.params.id)) return res.status(400).json({ error: 'INVALID_ID' });
    const order = await withTenant(req.tenant.id, (db) => getOrder(db, req.params.id));
    if (!order) return res.status(404).json({ error: 'NOT_FOUND' });
    if (!config.invoiceFunctionUrl) return res.status(501).json({ error: 'INVOICE_FUNCTION_URL not configured' });
    const inv = await requestInvoice({
      id: order.id, customerName: order.customer_name, createdAt: order.created_at, totalCents: order.total_cents,
      items: order.items.map((i) => ({ name: i.name, quantity: i.quantity, unitPriceCents: i.unit_price_cents })),
    }, { tenantSlug: req.tenant.slug });
    await withTenant(req.tenant.id, (db) => db.query(
      `INSERT INTO invoice_logs (tenant_id, order_id, cold_start, instance_id, function_ms, roundtrip_ms, pdf_bytes)
       VALUES ($1,$2,$3,$4,$5,$6,$7)`,
      [req.tenant.id, order.id, inv.coldStart, inv.instanceId, inv.functionMs, inv.roundtripMs, inv.pdf.length]
    ));
    res.set({
      'content-type': 'application/pdf',
      'content-disposition': `inline; filename="invoice-${order.id.slice(0, 8)}.pdf"`,
      'x-cold-start': String(inv.coldStart), 'x-function-ms': String(inv.functionMs), 'x-roundtrip-ms': String(inv.roundtripMs),
    }).send(inv.pdf);
  } catch (e) { next(e); }
});

module.exports = router;
